export type Locale = keyof typeof messages
export type MessageKey = keyof typeof messages['zh-CN']
export type MessageParams = Record<string, string | number>
export type Translator = (key: MessageKey, params?: MessageParams) => string

export const defaultLocale: Locale = 'zh-CN'
export const supportedLocales = Object.keys(messages) as Locale[]

export function translateMessage(key: MessageKey, locale: Locale, params?: MessageParams): string {
  const bundle = messages[locale] ?? messages[defaultLocale]
  const template = bundle[key] ?? messages[defaultLocale][key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}
